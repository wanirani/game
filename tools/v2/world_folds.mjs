// WORLD-2: plans which small materials of each area chunk are drawn with a look-alike texture the chunk uses anyway (src/v2/env/mats.js FOLDS,
// docs/v2/ENV_KIT.md 18) and writes the plan to src/v2/world/folds.js, so that the game never pays for the counting pass at load time.
//   node tools/v2/world_folds.mjs           write src/v2/world/folds.js
//   node tools/v2/world_folds.mjs --check   exit 1 when the stored plan differs from a fresh one (run it after changing an area or FOLDS)
import fs from 'node:fs';
import { loadPropsNode } from './world_node.mjs';
loadPropsNode();
const { AREAS } = await import('../../src/v2/world/index.js');
const { compileEnv } = await import('../../src/v2/env/build.js');
const FILE = new URL('../../src/v2/world/folds.js', import.meta.url), plan = {};
for (const id of Object.keys(AREAS)) {
  const a = await AREAS[id](), base = compileEnv(a.stage, { fold: false }), W = compileEnv(a.stage, { fold: 'auto' });
  plan[id] = W.env.stats.folds ?? {};
  const d = (st) => Object.fromEntries(Object.entries(st.chunks).map(([c, v]) => [c, v.draws]));
  console.log(id.padEnd(16), 'draws per chunk', JSON.stringify(d(base.env.stats)), '->', JSON.stringify(d(W.env.stats)), '· triangles', base.env.stats.tris, '->', W.env.stats.tris);
}
const body = `// GENERATED by tools/v2/world_folds.mjs - do not edit by hand (node tools/v2/world_folds.mjs; --check compares).
// Per area and chunk: a texture with few triangles -> the look-alike material it is drawn with (src/v2/env/mats.js FOLDS, docs/v2/ENV_KIT.md 18).
export const AREA_FOLDS = ${JSON.stringify(plan, null, 2)};
`;
if (process.argv.includes('--check')) {
  const old = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8') : '';
  if (old !== body) { console.error('✗ src/v2/world/folds.js is stale: run node tools/v2/world_folds.mjs'); process.exit(1); }
  console.log('fold plan up to date');
} else { fs.writeFileSync(FILE, body); console.log('wrote src/v2/world/folds.js'); }
