// 거울(역행): MML 선율을 음 단위로 뒤집는다 (o < > l, 음·쉼표·점음표만 — 붙임줄/반복/화음/v q k 미지원)
function retro(src) {
  const out = []; let o = 4, l = '4';
  for (const m of String(src).matchAll(/o(\d)|([<>])|l(\d+\.*)|([a-gr])([+#-]*)(\d*)(\.*)/g)) {
    if (m[1]) o = +m[1];
    else if (m[2]) o += m[2] === '>' ? 1 : -1;
    else if (m[3]) l = m[3];
    else { const len = (m[6] || l) + m[7]; out.push(m[4] === 'r' ? 'r' + len : `o${o} ${m[4]}${m[5]}${len}`); }
  }
  return out.reverse().join(' ');
}
