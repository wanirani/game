const dot = (n) => '.'.repeat(n);
const clean = (s) => String(s).replace(/[\s|]+/g, '');
// 1마디 패턴을 bars 마디로 늘리고 마지막 마디를 필인으로 교체, 첫 박 크래시
function drums(base, bars = 4, fill = null, crash = true) {
  const keys = new Set([...Object.keys(base), ...Object.keys(fill || {})]); keys.delete('step');
  let len = 0;
  for (const k of keys) if (base[k]) len = Math.max(len, clean(base[k]).length);
  const out = { step: base.step ?? 16 };
  for (const k of keys) {
    const b = base[k] ? clean(base[k]) : dot(len), f = fill && fill[k] != null ? clean(fill[k]) : b;
    out[k] = fill ? b.repeat(bars - 1) + f : b.repeat(bars);
  }
  if (crash) { const c = out.c || dot(len * bars); out.c = 'X' + c.slice(1); }
  return out;
}
