/** NPC 대화 스크립트 선택 (챕터/플래그/장소에 따라)
 *  1) 특수 상황(퀘스트 전달 등) → 2) 스테이지 전용 <npcId>_<stageId> → 3) 현재 챕터 이하의 가장 최근 _ch<N> (처음 한 번)
 *  → 4) default/팁/최근 챕터 대사 순환. stageId 는 대화가 일어난 World 의 스테이지 id (마을이면 생략) */
const recentTalk = new Map(); // npcId → { id, t, state } : 같은 대화에서 여러 번 불려도(마을 허브의 존재 확인 + 대화 장면) 같은 결과를 돌려준다
export function resolveNpcScript(npcId, state, stageId) {
  const now = Date.now();
  const r = recentTalk.get(npcId);
  if (r && r.state === state && now - r.t < 1500) return r.id;
  const id = pickNpcScript(npcId, state, stageId);
  recentTalk.set(npcId, { id, t: now, state });
  return id;
}
function pickNpcScript(npcId, state, stageId) {
  const p = state?.progress;
  const ch = p?.chapter ?? 0;
  if (npcId === 'npc_alberto' && state?.quests?.active?.el_letter && !p?.flags?.letter_delivered) return 'npc_alberto_letter';
  if (stageId && SCRIPTS[`${npcId}_${stageId}`]) return `${npcId}_${stageId}`; // 스테이지 안에서 만났을 때 전용 대사
  let latest = null;
  for (let k = ch; k >= 0; k--) if (SCRIPTS[`${npcId}_ch${k}`]) { latest = `${npcId}_ch${k}`; break; }
  // 외전은 장을 올리지 않는다 — 「시드는 장미」 뒤 카밀라는 외전 뒤 대사가 가장 새 대사 (story_ex.js npc_carmilla_ex24, ex_s24.md §10)
  if (npcId === 'npc_carmilla' && p?.flags?.ex_s24_done && SCRIPTS.npc_carmilla_ex24) latest = 'npc_carmilla_ex24';
  const seen = p?.seenScripts;
  if (latest && seen && !seen.includes(latest)) { seen.push(latest); p.npcTalks ??= {}; p.npcTalks[npcId] = 0; return latest; } // 다음 대화부터 팁 순환
  if (latest && !seen) return latest;
  const pool = [];
  if (latest && !SCRIPTS[latest].some((l) => l.cmd === 'give' || l.cmd === 'gold' || l.cmd === 'unlockChar')) pool.push(latest);
  if (SCRIPTS[`${npcId}_default`]) pool.push(`${npcId}_default`);
  for (let i = 1; i <= 6; i++) if (SCRIPTS[`${npcId}_tip${i}`]) pool.push(`${npcId}_tip${i}`);
  if (!pool.length) return `${npcId}_default`;
  let n = 0;
  if (p) { p.npcTalks ??= {}; n = p.npcTalks[npcId] = (p.npcTalks[npcId] ?? -1) + 1; }
  return pool[n % pool.length];
}

/** 스테이지 클리어 후 재생할 엔딩 스크립트 id (없으면 null)
 *  s12: 유물 5개 → null(심연의 문이 열려 s13 으로) / 11장의 "마지막 기회"에 카밀라를 믿음(carmilla_trust2) → ending_normal / 아니면 ending_bad
 *       (6장에서만 믿고 11장에서 거절하면 배드 엔딩 — ending_bad 의 "처음엔 믿어 주더니…" 대사가 이 경우)
 *  s13: ending_true   (엔딩 대사는 abyss_open 플래그에 따라 13장 안내로 분기하므로, s12 뒤에 엔딩을 틀어도 모순이 없다)
 *  s20: 별의 조각 6개(progress.shards, 또는 그 결과인 stars_all 플래그) → ending_p2true (새벽의 별) / 아니면 ending_p2 (파수꾼의 밤)  [world2 §2.3] */
export function endingAfter(stageId, state) {
  const p = state?.progress ?? {};
  const f = p.flags ?? {};
  if (stageId === 's20') return (p.shards?.length ?? 0) >= 6 || f.stars_all ? 'ending_p2true' : 'ending_p2';   // [hook:p2]
  if (stageId === 's13') return 'ending_true';
  if (stageId !== 's12') return null;
  if (f.relics_all || (p.relics?.length ?? 0) >= 5) return null;
  return f.carmilla_trust2 ? 'ending_normal' : 'ending_bad';
}

