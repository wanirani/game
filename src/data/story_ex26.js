const N = (text, x) => ({ who: 'narrator', text, ...x });
const H = (text, x) => ({ who: 'hero', text, ...x });
const S = (who, text, x) => ({ who, text, ...x });
const cg = (id = null) => ({ cmd: 'cg', id });
const bg = (id) => ({ cmd: 'bg', id }); // 컷신 전용 (대화 오버레이는 무시)
const bgm = (id) => ({ cmd: 'music', id });
const se = (id) => ({ cmd: 'sfx', id });
const quake = (power = 8, time = 0.5, color) => ({ cmd: 'shake', power, time, ...(color ? { color } : {}) });
const flag = (key, value = true) => ({ cmd: 'flag', key, value });
const title = (text, sub) => ({ cmd: 'title', text, sub }); // 컷신 전용 제목 카드
const L = (label) => ({ label });
const go = (label) => ({ goto: label });
const ifChar = (c, label) => ({ if: { char: c }, cmd: 'goto', label });
const ifFlag = (f, label) => ({ if: f, cmd: 'goto', label });
// 합류 전 영웅이 NPC로 말할 때 (story.js 의 R 과 같은 모양)
const R = (who, text, x) => ({ who, text, side: 'right', ...x });
// 조건부 한 줄 (플래그가 켜졌을 때 / 꺼졌을 때)
const IF = (f, who, text, x) => ({ if: f, who, text, ...x });
const NIF = (f, text) => ({ if: f, who: 'narrator', text });

